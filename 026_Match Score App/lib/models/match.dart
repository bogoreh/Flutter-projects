class Match {
  String team1Name;
  String team2Name;
  int team1Score;
  int team2Score;
  String status;
  DateTime matchTime;

  Match({
    required this.team1Name,
    required this.team2Name,
    required this.team1Score,
    required this.team2Score,
    required this.status,
    required this.matchTime,
  });
}